"""Section 6 — Find openly available paper PDFs WITHOUT an LLM.

Input:  papers.csv generated by 04_research_agent.py
Output: papers/*.pdf and pdf_manifest.csv

For each paper:
  1. Look up its OpenAlex work by OpenAlex ID or DOI.
  2. Try PDF URLs from OpenAlex open-access locations.
  3. If needed, inspect permitted landing-page HTML for PDF links.
  4. Download and validate a real, readable PDF.
  5. Record success or failure, plus links for manual follow-up.

No Google Scholar scraping, login automation, CAPTCHA bypass, or paywall bypass.
Google Scholar URLs are supplied only for manual searching.
"""

import argparse
import csv
import os
import re
import time
from pathlib import Path
from urllib.parse import quote, urlencode, urljoin, urlparse, parse_qsl, urlunparse
from urllib.robotparser import RobotFileParser

import pymupdf
import requests
from bs4 import BeautifulSoup

USER_AGENT = "Workshop03PaperFinder/1.0 (educational open-access PDF finder)"
OPENALEX_API = "https://api.openalex.org/works/"
SEMANTIC_SCHOLAR_API = "https://api.semanticscholar.org/graph/v1/paper/"
EUROPE_PMC_API = "https://www.ebi.ac.uk/europepmc/webservices/rest/search"
MAX_HTML_BYTES = 2 * 1024 * 1024
MAX_LANDING_PAGES = 3
MAX_PDF_ATTEMPTS = 8
MANIFEST_COLUMNS = [
    "title", "doi", "openalex_url", "status", "pdf_path",
    "source_pdf_url", "candidate_pdf_url", "manual_url", "scholar_url",
    "research_status", "error",
]


def parse_args():
    parser = argparse.ArgumentParser(
        description="Find open PDFs for Section 4 papers, then save a download report."
    )
    parser.add_argument("--input", type=Path, default=Path("papers.csv"))
    parser.add_argument("--output-dir", type=Path, default=Path("papers"))
    parser.add_argument("--manifest", type=Path, default=Path("pdf_manifest.csv"))
    parser.add_argument(
        "--limit", type=int, default=0,
        help="Maximum number of CSV rows to try (0 = all rows).",
    )
    parser.add_argument(
        "--max-pdf-mb", type=int, default=40,
        help="Maximum size of one PDF in MB (default: 40).",
    )
    return parser.parse_args()


def public_http_url(url: str) -> bool:
    """Accept only public-looking HTTP URLs; never load local files or localhost."""
    try:
        parsed = urlparse(url)
        host = (parsed.hostname or "").lower()
        if parsed.scheme not in ("http", "https") or not host:
            return False
        if parsed.username or parsed.password or parsed.port not in (None, 80, 443):
            return False
        if host in ("localhost", "localhost.localdomain") or host.endswith(".local"):
            return False
        # Do not follow IP-address links (including private-network addresses).
        if re.fullmatch(r"[0-9.]+", host) or ":" in host:
            return False
        return True
    except ValueError:
        return False


def unique_urls(urls):
    seen = set()
    result = []
    for url in urls:
        if not isinstance(url, str):
            continue
        url = url.strip()
        if not public_http_url(url) or url in seen:
            continue
        seen.add(url)
        result.append(url)
    return result


def scholar_search_url(title: str) -> str:
    return "https://scholar.google.com/scholar?" + urlencode({"q": title})


def work_lookup_paths(row):
    """The Section 4 CSV stores DOI URLs and OpenAlex work URLs."""
    paths = []
    url = str(row.get("openalex_url") or "")
    match = re.search(r"(?:^|/)W[0-9]+/?$", url, flags=re.I)
    if match:
        paths.append(match.group(0).strip("/"))
    doi = str(row.get("doi") or "").strip()
    doi = re.sub(r"^https?://(?:dx\.)?doi\.org/", "", doi, flags=re.I)
    doi = re.sub(r"^doi:\s*", "", doi, flags=re.I).strip()
    if doi.startswith("10.") and "/" in doi:
        paths.append("https://doi.org/" + quote(doi, safe="/"))
    return list(dict.fromkeys(paths)), doi


def openalex_work(session, row):
    paths, _doi = work_lookup_paths(row)
    if not paths:
        raise ValueError("The CSV row has no usable OpenAlex work ID or DOI")

    key = os.getenv("OPENALEX_API_KEY")
    params = {"api_key": key} if key else None
    errors = []
    for path in paths:
        # The work ID and DOI refer to the same record; try the alternate ID on failure.
        try:
            response = session.get(
                OPENALEX_API + path, params=params, timeout=(8, 20)
            )
            response.raise_for_status()
            record = response.json()
            if not isinstance(record, dict) or not record.get("id"):
                raise ValueError("Unexpected OpenAlex JSON response")
            return record
        except (requests.RequestException, ValueError) as exc:
            errors.append(f"OpenAlex lookup ({path}): {type(exc).__name__}")
    raise ValueError("; ".join(errors))


def openalex_locations(work):
    """Prioritize open-access PDF links, then collect OA landing pages."""
    locations = []
    best = work.get("best_oa_location")
    if isinstance(best, dict):
        locations.append(best)
    for location in work.get("locations") or []:
        if isinstance(location, dict) and location.get("is_oa"):
            locations.append(location)

    pdf_urls = unique_urls(loc.get("pdf_url") for loc in locations)
    page_urls = unique_urls(loc.get("landing_page_url") for loc in locations)
    # The publisher DOI page can be a useful last fallback even without an OA URL.
    doi = work.get("doi")
    if isinstance(doi, str) and public_http_url(doi):
        page_urls = unique_urls([*page_urls, doi])
    return pdf_urls, page_urls


def additional_open_pdf_sources(session, doi):
    """Check independent scholarly APIs, without scraping their search pages.

    Both APIs are optional fallbacks. HTTP 429, 404, timeouts, and missing
    metadata are ordinary failures, not reasons to stop other papers.
    """
    if not doi:
        return [], [], []
    pdfs, pages, issues = [], [], []

    try:
        endpoint = SEMANTIC_SCHOLAR_API + "DOI:" + quote(doi, safe="/")
        headers = {}
        if os.getenv("SEMANTIC_SCHOLAR_API_KEY"):
            headers["x-api-key"] = os.environ["SEMANTIC_SCHOLAR_API_KEY"]
        response = session.get(
            endpoint, params={"fields": "title,openAccessPdf,isOpenAccess,url"},
            headers=headers, timeout=(8, 15),
        )
        response.raise_for_status()
        info = response.json()
        if isinstance(info, dict):
            open_pdf = info.get("openAccessPdf")
            if isinstance(open_pdf, dict) and open_pdf.get("url"):
                pdfs.append(open_pdf["url"])
            if isinstance(info.get("url"), str):
                pages.append(info["url"])
    except (requests.RequestException, ValueError) as exc:
        issues.append(f"Semantic Scholar: {short_error(exc)}")

    try:
        response = session.get(
            EUROPE_PMC_API, params={"query": f"DOI:{doi}", "format": "json",
                                    "resultType": "core", "pageSize": 3},
            timeout=(8, 15),
        )
        response.raise_for_status()
        data = response.json()
        matches = data.get("resultList", {}).get("result", [])
        for match in matches:
            # Only use the matching DOI and articles confirmed OA by Europe PMC.
            found_doi = str(match.get("doi") or "").lower().strip()
            if found_doi != doi.lower() or str(match.get("isOpenAccess", "")).upper() != "Y":
                continue
            pmcid = str(match.get("pmcid") or "")
            if re.fullmatch(r"PMC[0-9]+", pmcid):
                pages.append("https://europepmc.org/articles/" + pmcid)
                pdfs.append("https://europepmc.org/articles/" + pmcid + "?pdf=render")
            for full_text in (match.get("fullTextUrlList") or {}).get("fullTextUrl", []):
                if (str(full_text.get("documentStyle", "")).lower() == "pdf"
                        and full_text.get("url")):
                    pdfs.append(full_text["url"])
    except (requests.RequestException, ValueError, TypeError, AttributeError) as exc:
        issues.append(f"Europe PMC: {short_error(exc)}")

    return unique_urls(pdfs), unique_urls(pages), issues


def redact_api_keys(url):
    """Never put the optional OpenAlex credential into manifest URLs."""
    parsed = urlparse(url)
    query = [
        (k, v) for k, v in parse_qsl(parsed.query, keep_blank_values=True)
        if k.lower() not in {"api_key", "apikey", "access_token"}
    ]
    return urlunparse(parsed._replace(query=urlencode(query)))


class RobotsPolicy:
    """Read robots.txt once per domain and respect its published crawl-delay."""

    def __init__(self, session):
        self.session = session
        self.parsers = {}
        self.next_request = {}

    def allowed(self, url):
        if not public_http_url(url):
            return False, "Unsupported or non-public URL"
        parsed = urlparse(url)
        site = f"{parsed.scheme}://{parsed.netloc}"
        if site not in self.parsers:
            robots_url = site + "/robots.txt"
            try:
                response = self.session.get(robots_url, timeout=(6, 10))
                if response.status_code in (404, 410):
                    self.parsers[site] = None  # No robots policy published.
                elif response.status_code == 200:
                    parser = RobotFileParser()
                    parser.parse(response.text.splitlines())
                    self.parsers[site] = parser
                else:
                    return False, f"robots.txt unavailable (HTTP {response.status_code})"
            except requests.RequestException:
                return False, "Could not check robots.txt"
        parser = self.parsers[site]
        if parser is not None and not parser.can_fetch(USER_AGENT, url):
            return False, "robots.txt disallows automated access"

        # Wait only when this domain publishes a Crawl-delay.
        delay = parser.crawl_delay(USER_AGENT) if parser else None
        if delay:
            now = time.monotonic()
            time.sleep(max(0, self.next_request.get(site, now) - now))
            self.next_request[site] = time.monotonic() + delay
        return True, ""


def validate_pdf(path: Path):
    """A .pdf suffix or HTTP 200 is not enough to prove a PDF is readable."""
    with path.open("rb") as handle:
        if b"%PDF-" not in handle.read(1024):
            raise ValueError("Response was not a PDF file")
    with pymupdf.open(path) as document:
        if document.needs_pass or len(document) < 1:
            raise ValueError("PDF is encrypted or has no readable pages")


def get_public_resource(session, robots, url, accept, timeout, api_key=None):
    """Check each redirect against robots.txt before requesting its destination."""
    current = url
    for _ in range(6):
        allowed, explanation = robots.allowed(current)
        if not allowed:
            raise ValueError(explanation)
        # Send an OpenAlex key only to the official cached-content domain.
        params = ({"api_key": api_key}
                  if api_key and urlparse(current).hostname == "content.openalex.org"
                  else None)
        response = session.get(
            current, headers={"Accept": accept}, params=params,
            timeout=timeout, stream=True, allow_redirects=False,
        )
        if response.status_code in (301, 302, 303, 307, 308):
            location = response.headers.get("Location")
            destination = urljoin(current, location) if location else ""
            response.close()
            if not public_http_url(destination):
                raise ValueError("Redirected to an unsupported URL")
            current = destination
            continue
        try:
            response.raise_for_status()
            if response.status_code >= 300:
                raise ValueError(f"Unexpected HTTP {response.status_code}")
            return response
        except BaseException:
            response.close()
            raise
    raise ValueError("Too many HTTP redirects")


def download_pdf(session, robots, url, target, max_bytes, api_key=None):
    target.parent.mkdir(parents=True, exist_ok=True)
    temp = target.with_suffix(".pdf.part")
    final_url = url
    try:
        with get_public_resource(session, robots, url, "application/pdf,*/*",
                                 (8, 30), api_key=api_key) as response:
            final_url = response.url
            length = response.headers.get("Content-Length")
            if length and length.isdigit() and int(length) > max_bytes:
                raise ValueError("PDF exceeds size limit")

            downloaded = 0
            with temp.open("wb") as output:
                for chunk in response.iter_content(chunk_size=65536):
                    if not chunk:
                        continue
                    downloaded += len(chunk)
                    if downloaded > max_bytes:
                        raise ValueError("PDF exceeds size limit")
                    output.write(chunk)

        validate_pdf(temp)
        temp.replace(target)
        return redact_api_keys(final_url)
    finally:
        temp.unlink(missing_ok=True)


def extract_pdf_urls(html: str, page_url: str):
    """Parse common scholarly HTML patterns; no browser/JavaScript execution."""
    soup = BeautifulSoup(html, "html.parser")
    candidates = []

    for tag in soup.find_all("meta"):
        name = str(tag.get("name", "")).lower()
        if name in {"citation_pdf_url", "dc.identifier.pdf", "eprints.document_url"}:
            candidates.append(urljoin(page_url, tag.get("content", "")))

    for tag in soup.find_all("link"):
        if "pdf" in str(tag.get("type", "")).lower():
            candidates.append(urljoin(page_url, tag.get("href", "")))

    for tag in soup.find_all("a"):
        href = tag.get("href")
        if not href:
            continue
        label = tag.get_text(" ", strip=True).lower()
        address = href.lower()
        if (
            re.search(r"\.pdf(?:$|[?#])", address)
            or re.search(r"(?:^|/)pdf(?:/|$|[?#])", address)
            or "download pdf" in label
            or label in {"pdf", "full text pdf", "view pdf"}
        ):
            candidates.append(urljoin(page_url, href))

    for tag in soup.find_all(["iframe", "embed"]):
        src = tag.get("src", "")
        if re.search(r"\.pdf(?:$|[?#])", src, flags=re.I):
            candidates.append(urljoin(page_url, src))

    return unique_urls(candidates)[:5]


def scrape_landing_page(session, robots, url):
    with get_public_resource(session, robots, url,
                             "text/html,application/xhtml+xml", (8, 20)) as response:
        content_type = response.headers.get("Content-Type", "").lower()
        if "pdf" in content_type:
            return [response.url]
        if content_type and not any(
            kind in content_type for kind in ("html", "text/plain", "xml")
        ):
            raise ValueError("Landing page did not return HTML")
        data = bytearray()
        for chunk in response.iter_content(chunk_size=32768):
            data.extend(chunk)
            if len(data) > MAX_HTML_BYTES:
                raise ValueError("Landing page too large to parse")
        response.encoding = response.encoding or "utf-8"
        return extract_pdf_urls(bytes(data).decode(response.encoding, errors="replace"),
                                response.url)


def short_error(exc):
    if isinstance(exc, requests.HTTPError) and exc.response is not None:
        return f"HTTP {exc.response.status_code}"
    if isinstance(exc, requests.Timeout):
        return "Request timed out"
    if isinstance(exc, requests.RequestException):
        return "Network/request failure"
    return str(exc)[:160]


def safe_filename(index, title):
    slug = re.sub(r"[^a-z0-9]+", "_", title.lower()).strip("_")[:48].strip("_")
    return f"paper_{index:03d}_{slug or 'untitled'}.pdf"


def process_paper(session, robots, row, index, output_dir, max_bytes):
    title = (row.get("title") or "").strip()
    paths, doi = work_lookup_paths(row)
    openalex_url = (row.get("openalex_url") or "").strip()
    scholar = scholar_search_url(title or doi)
    manual_url = (
        "https://doi.org/" + quote(doi, safe="/") if doi
        else openalex_url if public_http_url(openalex_url) else scholar
    )
    record = {
        "title": title, "doi": doi, "openalex_url": openalex_url,
        "status": "FAILED", "pdf_path": "", "source_pdf_url": "",
        "candidate_pdf_url": "", "manual_url": manual_url, "scholar_url": scholar,
        "research_status": "UNKNOWN", "error": "",
    }
    errors = []
    target = output_dir / safe_filename(index, title)
    if target.exists():
        try:
            validate_pdf(target)
            record.update(status="EXISTING", pdf_path=str(target))
            return record
        except (OSError, ValueError, RuntimeError):
            errors.append("Existing file was invalid; retrying download")

    pdf_urls, pages = [], []
    try:
        work = openalex_work(session, row)
        record["doi"] = (work.get("doi") or doi).removeprefix("https://doi.org/")
        record["research_status"] = ("RETRACTED" if work.get("is_retracted") is True
                                     else "NOT_FLAGGED" if work.get("is_retracted") is False
                                     else "UNKNOWN")
        if record["research_status"] == "RETRACTED":
            print("  [ACADEMIC WARNING] OpenAlex flags this paper as retracted.")
        pdf_urls, pages = openalex_locations(work)
        # OpenAlex's own cached OA PDFs use a separate content endpoint.
        # Only attempt it when a free OPENALEX_API_KEY is configured.
        cache_pdf = (work.get("content_urls") or {}).get("pdf")
        if (os.getenv("OPENALEX_API_KEY")
                and (work.get("has_content") or {}).get("pdf")
                and isinstance(cache_pdf, str)):
            pdf_urls = unique_urls([cache_pdf, *pdf_urls])
    except (requests.RequestException, OSError, ValueError, RuntimeError) as exc:
        errors.append(f"OpenAlex: {short_error(exc)}")
        # Even if OpenAlex fails, a DOI from Section 4 may lead to a public page.
        if doi:
            pages = ["https://doi.org/" + quote(doi, safe="/")]

    if pages:
        record["manual_url"] = pages[0]

    # Independent sources: useful when a publisher returns HTTP 403.
    # A lookup failure must never prevent the original sources from working.
    other_pdfs, other_pages, provider_errors = additional_open_pdf_sources(
        session, record["doi"]
    )
    pdf_urls = unique_urls([*pdf_urls, *other_pdfs])
    pages = unique_urls([*pages, *other_pages])
    errors.extend(provider_errors)

    attempted_urls = set()
    attempts = 0

    def try_pdf(url):
        nonlocal attempts
        if url in attempted_urls or attempts >= MAX_PDF_ATTEMPTS:
            return False
        attempted_urls.add(url)
        attempts += 1
        if not record["candidate_pdf_url"]:
            record["candidate_pdf_url"] = url
        try:
            key = (os.getenv("OPENALEX_API_KEY")
                   if urlparse(url).hostname == "content.openalex.org" else None)
            resolved = download_pdf(session, robots, url, target, max_bytes,
                                    api_key=key)
            record.update(status="DOWNLOADED", pdf_path=str(target),
                          source_pdf_url=resolved, error="")
            return True
        except (requests.RequestException, OSError, ValueError, RuntimeError) as exc:
            errors.append(f"PDF {url}: {short_error(exc)}")
            return False

    # Direct OA PDFs are always attempted before scraping landing pages.
    for url in pdf_urls:
        if try_pdf(url):
            return record

    for page_url in pages[:MAX_LANDING_PAGES]:
        try:
            discovered = scrape_landing_page(session, robots, page_url)
            if not discovered:
                errors.append(f"Page {page_url}: No PDF link found in HTML")
            for candidate in discovered:
                if try_pdf(candidate):
                    return record
        except (requests.RequestException, OSError, ValueError, RuntimeError) as exc:
            errors.append(f"Page {page_url}: {short_error(exc)}")

    # Do not infer "login required" or "paywalled" from a failed request.
    record["error"] = (
        "Automatic PDF download unavailable; manual review needed. "
        + (" | ".join(errors[:3]) if errors else "No public PDF link available.")
    )[:700]
    return record


def main():
    args = parse_args()
    if args.limit < 0 or args.max_pdf_mb < 1:
        raise SystemExit("--limit must be >= 0 and --max-pdf-mb must be >= 1")
    if not args.input.is_file():
        raise SystemExit(f"Input CSV not found: {args.input}. Run Section 4 first.")

    with args.input.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        if not reader.fieldnames or "title" not in reader.fieldnames:
            raise SystemExit("Expected a Section 4 papers.csv containing a title column.")
        rows = list(reader)

    if args.limit:
        rows = rows[:args.limit]
    args.output_dir.mkdir(parents=True, exist_ok=True)
    args.manifest.parent.mkdir(parents=True, exist_ok=True)

    session = requests.Session()
    session.headers.update({"User-Agent": USER_AGENT})
    session.max_redirects = 5
    robots = RobotsPolicy(session)
    counts = {"DOWNLOADED": 0, "EXISTING": 0, "FAILED": 0}

    # Write after each paper so one failure or interruption never loses earlier results.
    with args.manifest.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=MANIFEST_COLUMNS)
        writer.writeheader()
        for index, row in enumerate(rows, start=1):
            print(f"[PAPER {index}/{len(rows)}] {(row.get('title') or '(untitled)')[:90]}")
            try:
                result = process_paper(session, robots, row, index, args.output_dir,
                                       args.max_pdf_mb * 1024 * 1024)
            except Exception as exc:
                # Per-row safety net: report unexpected errors and continue.
                result = {
                    "title": row.get("title") or "", "doi": row.get("doi") or "",
                    "openalex_url": row.get("openalex_url") or "",
                    "status": "FAILED", "pdf_path": "", "source_pdf_url": "",
                    "candidate_pdf_url": "", "manual_url": row.get("doi") or row.get("openalex_url") or "",
                    "scholar_url": scholar_search_url(row.get("title") or ""),
                    "research_status": "UNKNOWN",
                    "error": f"Unexpected error ({type(exc).__name__}); manual review needed",
                }
            writer.writerow(result)
            handle.flush()
            counts[result["status"]] += 1
            print(f"  [{result['status']}] {result['pdf_path'] or result['error'][:130]}")

    print(f"\n[REPORT] {args.manifest}")
    print(f"[SUMMARY] downloaded={counts['DOWNLOADED']}, "
          f"existing={counts['EXISTING']}, failed={counts['FAILED']}")
    print("[MANUAL] For failed rows, open manual_url or scholar_url. "
          "No Google Scholar pages are scraped.")


if __name__ == "__main__":
    main()
